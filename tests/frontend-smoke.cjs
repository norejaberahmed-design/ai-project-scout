const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const html = fs.readFileSync("site/index.html", "utf8");
const match = html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(match, "inline app script must exist");
assert.match(html, /id="modelprovider"/, "chat UI must expose model provider selection");
assert.match(match[1], /fetch\(apiBase\+"\/api\/providers"/, "UI must load safe provider configuration status");
assert.match(match[1], /JSON\.stringify\(\{question:q,provider:modelProvider\.value,history:conversationHistory\.slice\(-8\)\}\)/, "chat request must send the selected provider and bounded conversation history");
assert.match(match[1], /scoutModelProvider/, "provider preference may be saved without storing API keys");
assert.match(html, /id="view-components"/, "component acquisition view must exist");
assert.match(match[1], /\/api\/components\/inspect/, "UI must call component inspection API");
assert.match(match[1], /\/api\/components\/acquire/, "UI must call guarded acquisition API");
assert.match(match[1], /Authorization.*Bearer/, "acquisition token must be sent as an authorization header");
assert.doesNotMatch(match[1], /localStorage\.(?:setItem|getItem)\([^)]*component-token/i,
  "admin import token must not be persisted in localStorage");

// Regression guard: public-web queries and skill harvesting are separate pipelines.
const script = match[1];
const submitStart = script.indexOf("async function submit(text){");
const submitEnd = script.indexOf('$("form").addEventListener("submit"', submitStart);
assert.ok(submitStart >= 0 && submitEnd > submitStart, "submit handler must exist");
const submitHandler = script.slice(submitStart, submitEnd);
assert.ok(submitHandler.includes("searchBrowserSources(q)"), "disconnected UI must run real public-source searches instead of only showing search links");
assert.ok(!submitHandler.includes("searchGitHubSkills(q)"), "general user queries must not be routed to GitHub skill discovery");
assert.ok(!submitHandler.includes("searchGitHubRepositories"), "user answers must never search GitHub repositories");
assert.ok(!submitHandler.includes("api.github.com/search/repositories"), "GitHub repository metadata must not be answer evidence");
assert.ok(submitHandler.includes('fetch(apiBase+"/api/chat"'), "chat must call the answer backend");
assert.ok(submitHandler.includes('fetch(apiBase+"/api/search"'), "chat must show public-web results if model chat fails");
assert.ok(script.includes("async function searchWikipedia(q)"), "no-backend fallback must fetch real Wikipedia results");
assert.ok(script.includes("async function searchHackerNews(q)"), "no-backend fallback must search Hacker News");
assert.ok(script.includes("async function searchStackExchange(q)"), "software fallback must search Stack Exchange");
assert.ok(script.includes("async function searchCrossref(q)"), "research fallback must search Crossref");
assert.ok(script.includes("async function searchOpenAlex(q)"), "research fallback must search OpenAlex");
assert.ok(script.includes("async function searchNpm(q)"), "software fallback must search npm Registry");
const browserSearchStart = script.indexOf("async function searchBrowserSources(q){");
const browserSearchEnd = script.indexOf("async function submit(text){", browserSearchStart);
const browserSearch = script.slice(browserSearchStart, browserSearchEnd);
assert.ok(browserSearchStart >= 0 && browserSearchEnd > browserSearchStart, "public search fallback must exist");
assert.ok(!browserSearch.includes("github.com") && !browserSearch.includes("api.github.com"), "general public search must not query GitHub APIs; GitHub is only for skill discovery");
assert.ok(browserSearch.includes("Promise.allSettled"), "search should return partial results when one provider is unavailable");
assert.ok(script.includes("https://ar.wikipedia.org/w/api.php?"), "fallback must query Arabic Wikipedia");
assert.ok(script.includes("https://en.wikipedia.org/w/api.php?"), "fallback must query English Wikipedia");
assert.ok(!script.includes("https://www.youtube.com/results?search_query="), "skill discovery must not add video search");
assert.ok(script.includes('fetch(apiBase+"/api/skills/discover"'), "skill harvesting must use the backend skill pipeline");
assert.ok(script.includes("async function discoverGitHubSkillFiles()"), "disconnected skill discovery must query GitHub directly");
assert.ok(script.includes("/search/repositories?"), "direct skill discovery must use the public GitHub repository search API");
assert.ok(script.includes('"/git/trees/"+revision'), "direct discovery must inspect a pinned GitHub tree revision");
assert.ok(script.includes("لم يُفحص بعد؛ لم تُنسخ المهارة"), "direct discovery must not imply unverified skills were copied");
assert.ok(script.includes("SKILL.md"), "skill discovery must target skill files, not repository metadata alone");
assert.ok(script.includes("روابط مباشرة وليست نتائج بحث مسترجعة"), "UI must disclose when links are not fetched results");
assert.ok(html.includes("تغطية البحث في هذه الإجابة"), "UI must show an Arabic source coverage summary");
assert.ok(html.includes("ليس قياسًا لتغطية الإنترنت كله"), "UI must not claim complete internet coverage");
new vm.Script(script, { filename: "site/index.html inline script" });
console.log("Frontend smoke checks passed: JavaScript syntax, API-backed chat, multi-source public web fallback with GitHub isolated to skill harvesting.");
